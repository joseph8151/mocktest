// Local dev without Cloudflare login: Workers AI has no local mode, so run `wrangler dev` with a copy of
// wrangler.jsonc that leaves out the AI binding (speaking answers then simply skip AI transcription locally).
// Usage: npm run dev [-- extra wrangler args]
import fs from 'node:fs';
import { spawn } from 'node:child_process';
const src = fs.readFileSync(new URL('../wrangler.jsonc', import.meta.url), 'utf8');
const out = src.replace(/^\s*"ai":\s*\{[^}]*\},?\s*$/m, '');
if (out === src) console.warn('dev.mjs: no "ai" binding found in wrangler.jsonc');
fs.writeFileSync(new URL('../wrangler.local.jsonc', import.meta.url), '// generated by scripts/dev.mjs — do not edit\n' + out);
spawn('npx', ['wrangler', 'dev', '-c', 'wrangler.local.jsonc', ...process.argv.slice(2)], { stdio: 'inherit' }).on('exit', (c) => process.exit(c ?? 0));
